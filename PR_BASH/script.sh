#!/bin/bash

# 1. Функція з власним текстом виводу
print_stage() {
    echo -e "\n---> [ ЕТАП: $1 ] <---"
}

# 2. Використання pipe для фільтрації процесів
print_stage "Фільтрація процесів (ps + grep)"
# Шукаємо процеси bash (дужки [b] потрібні, щоб grep не вивів сам себе)
ps aux | grep "[b]ash" | head -n 3

# 3. Створення власного масиву та вивід усіх елементів
print_stage "Робота з масивом"
# Масив з твоїх інструментів
my_stack=("Neovim" "Rust" "Fedora" "Blender" "Wayland")
echo "Усі елементи масиву: ${my_stack[@]}"

# 4. Застосування RegEx для фільтрації рядків
print_stage "Фільтрація через RegEx"
echo "Шукаємо в масиві слова, які закінчуються на 'land' або 'era':"
# printf виводить кожен елемент з нового рядка, а grep -E застосовує регулярку
printf "%s\n" "${my_stack[@]}" | grep -E "(land|era)$"

# 5. Змінений приклад з циклом та умовою (модифікація під себе)
print_stage "Цикл з умовами"
for item in "${my_stack[@]}"; do
    if [[ "$item" == "Rust" ]]; then
        echo "[+] $item: Ідеально для бекенду."
    elif [[ "$item" == "Fedora" ]]; then
        echo "[+] $item: Топовий дистрибутив для розробки."
    else
        echo "[-] $item: Просто хороший інструмент."
    fi
done

echo -e "\nСкрипт успішно завершив роботу. Ніякого сміття не залишено!"
